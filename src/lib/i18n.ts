const DICTS: Record<Lang, Dict> = { de, en };

export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  let s = DICTS[lang][key] ?? DICTS.de[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function formatTime(lang: Lang, d: Date): string {
  return d.toLocaleTimeString(lang === 'de' ? 'de-AT' : 'en-GB', { hour: '2-digit', minute: '2-digit' });
}

export function formatWhen(lang: Lang, d: Date, now = new Date()): string {
  const t = (k: string) => translate(lang, k);
  const sameDay = (a: Date, b: Date) => a.toDateString() === b.toDateString();
  const tomorrow = new Date(now.getFullYear(), now.getMonth(), now.getDate() + 1);
  if (sameDay(d, now)) return `${t('common.today')} ${formatTime(lang, d)}`;
  if (sameDay(d, tomorrow)) return `${t('common.tomorrow')} ${formatTime(lang, d)}`;
  return d.toLocaleString(lang === 'de' ? 'de-AT' : 'en-GB', {
    weekday: 'short', day: '2-digit', month: '2-digit', hour: '2-digit', minute: '2-digit',
  });
}

export function formatMoney(lang: Lang, n: number): string {
  return n.toLocaleString(lang === 'de' ? 'de-AT' : 'en-GB', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
}

export function formatDuration(ms: number): string {
  const neg = ms < 0;
  const total = Math.abs(Math.round(ms / 1000));
  const h = Math.floor(total / 3600);
  const m = Math.floor((total % 3600) / 60);
  const s = total % 60;
  const p = (n: number) => String(n).padStart(2, '0');
  return `${neg ? '-' : ''}${h > 0 ? `${h}:${p(m)}` : m}:${p(s)}`;
}

/** Dauer als „1 h 05 min“ bzw. „25 min“ */
export function formatHM(ms: number): string {
  const total = Math.max(0, Math.round(ms / 60000));
  const h = Math.floor(total / 60);
  const m = total % 60;
  return h > 0 ? `${h} h ${String(m).padStart(2, '0')} min` : `${m} min`;
}

/** ISO-Datum (JJJJ-MM-TT) in der Schreibweise der Sprache */
export function formatDate(lang: Lang, iso: string): string {
  const [y, m, d] = iso.split('-').map(Number);
  return new Date(y, m - 1, d).toLocaleDateString(lang === 'de' ? 'de-AT' : 'en-GB', { day: 'numeric', month: 'numeric', year: 'numeric' });
}
